for (const op of catalog.operations) {
  op.overview = { routeSelection: ['hermes', 'raptor'].includes(op.id), groups: groups[op.id] };
  // Keep recorded locations and evidence; presentation groups combine candidates rather than selecting them away.
  if (op.id === 'raptor') for (const set of op.pointSets.filter(s => s.stage === '出口接敌')) {
    for (const p of set.points) {
      const match = set.description.match(new RegExp(`${p.cell}\\s*([^、；]+)`));
      if (match) p.label = `${match[1].trim()} · ${p.cell}`;
    }
  }
}
