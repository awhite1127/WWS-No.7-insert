'use strict';
const {app,BrowserWindow,ipcMain}=require('electron');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const argument=process.argv.find(a=>a.startsWith('--package='));
const appRoot=argument?argument.slice(10):path.join(root,'source');
const {createNewsService}=require(path.join(appRoot,'electron/news-service.cjs'));
let now=Date.parse('2026-10-08T06:00:00Z'),requests=0,reads=0;
const blog={items:[{id:1,title:'Balance Changes',categories:['Balance Changes'],slug:'changes',publication_date:'2026-10-07',short_content:'Changes to ships.'}]};
const events={items:[{id:2,title:'15.9版本更新',description:'版本内容',slug:'update-159',category:21,published_at:Date.parse('2026-10-07')/1000}]};
const news=createNewsService({now:()=>now,fetchImpl:async url=>{requests++;return {ok:true,json:async()=>url.includes('blog.')?blog:url.includes('categories')?{items:[{id:21,slug:'game-updates'}]}:events};}});
const config={realm:'asia',theme:'dark',overlayEnabled:false,overlayHotkeyEnabled:true,overlayHotkey:'Tab',overlayBattleMode:'random',gamePath:''};
ipcMain.handle('ships:data-status',()=>({state:'idle',version:'',revision:0,shipCount:0,checkedAt:null,updated:false,error:''}));
app.setPath('userData',fs.mkdtempSync(path.join(require('node:os').tmpdir(),'no7-news-ui-')));
for(const [channel,handler] of Object.entries({'config:get':()=>config,'wg:auth-status':()=>({authorized:false}),'arena:get-state':()=>({arena:null,roster:[],visible:true}),'window:is-maximized':()=>false,'news:get':()=>{reads++;return news.get();},'news:detail':()=>['中文公告详情测试'],'news:open':()=>true}))ipcMain.handle(channel,handler);
const delay=ms=>new Promise(r=>setTimeout(r,ms));
const timeout=setTimeout(()=>app.exit(1),30000);app.on('will-quit',()=>clearTimeout(timeout));
app.whenReady().then(async()=>{
  await news.get();
  const win=new BrowserWindow({show:false,width:1450,height:980,webPreferences:{offscreen:true,backgroundThrottling:false,preload:path.join(appRoot,'electron/preload.cjs'),sandbox:true,contextIsolation:true}});
  win.webContents.on('console-message', details => { if(details.level==='error')console.error(details.message); });
  const js=async code=>{try{return await win.webContents.executeJavaScript(code);}catch(e){console.error('Failed UI step:',code);throw e;}};
  await win.loadFile(path.join(appRoot,'dist/index.html'));await delay(250);
  await js(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()==='暂不授权')?.click()`);
  const visit=async()=>{await js(`Array.from(document.querySelectorAll('.nav-item')).find(b=>b.textContent.includes('公告中心')).click()`);await delay(80);};
  await visit();
  if(!await js(`document.querySelector('.news-sync').textContent.includes('每次启动软件时更新一次') && !Array.from(document.querySelectorAll('.news-sync button')).length && document.querySelector('.news-card')`))throw Error('Incorrect startup policy UI');
  if(requests!==3||reads!==1)throw Error('Opening news triggered a second update');
  now+=24*60*60*1000;
  await js(`Array.from(document.querySelectorAll('.nav-item')).find(b=>b.textContent.includes('七号插')).click()`);await delay(50);
  await visit();
  if(requests!==3||reads!==2)throw Error('Revisiting news fetched new data');
  await js(`document.querySelector('.news-card__actions button').click()`);await delay(50);
  if(!await js(`document.querySelector('dialog[open]')?.textContent.includes('中文公告详情测试')`))throw Error('On-demand detail unavailable');
  await js(`document.querySelector('.news-modal__header button').click()`);
  fs.mkdirSync(path.join(root,'previews'),{recursive:true});
  fs.writeFileSync(path.join(root,'previews/news-startup-only.png'),(await win.webContents.capturePage()).toPNG());
  const view=fs.readFileSync(path.join(root,'source/src/components/NewsView.vue'),'utf8');
  const main=fs.readFileSync(path.join(appRoot,'electron/main.cjs'),'utf8');
  if(view.includes('setInterval')||/setInterval\([^\n]*newsService/.test(main))throw Error('News polling timer remains');
  console.log('News UI OK: one three-request startup update, cached page visits after 24 hours, no manual refresh or polling, detail remains accessible');
  app.exit(0);
}).catch(e=>{console.error(e);app.exit(1);});
